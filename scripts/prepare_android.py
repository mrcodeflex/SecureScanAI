#!/usr/bin/env python3
"""Prepare the Flutter Android platform folder (used by GitHub Actions and by developers).

Why this exists: the Gradle wrapper and Flutter's Gradle files are produced by `flutter create` and change between
Flutter releases, so they are generated by the Flutter SDK instead of being committed. This script
  1. finds the Flutter project (the folder whose pubspec.yaml depends on the Flutter SDK),
  2. runs `flutter create --platforms=android` if the android/ folder is missing,
  3. sets the application id to com.securescanai.app,
  4. copies the committed customisations from android_overrides/ (manifest, icon, network config, MainActivity).
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

APP_ID = "com.securescanai.app"
GENERATED_ID = "com.securescanai.securescan_ai"  # org + project name used by `flutter create`
TEXT_SUFFIXES = {".gradle", ".kts", ".xml", ".kt", ".java", ".properties", ".pro", ".yaml", ".yml"}


def find_project(root: Path, explicit: str | None) -> Path:
    if explicit:
        project = (root / explicit).resolve()
        if not (project / "pubspec.yaml").is_file():
            sys.exit(f"ERROR: no pubspec.yaml in {project}")
        return project
    for pubspec in sorted(root.rglob("pubspec.yaml")):
        parts = set(pubspec.parts)
        if parts & {"node_modules", ".dart_tool", "build", ".git"}:
            continue
        if "sdk: flutter" in pubspec.read_text(encoding="utf-8", errors="ignore"):
            return pubspec.parent
    sys.exit("ERROR: could not find a Flutter project (a pubspec.yaml containing 'sdk: flutter').")


def run(cmd: list[str], cwd: Path) -> None:
    print("+", " ".join(cmd), flush=True)
    subprocess.run(cmd, cwd=cwd, check=True)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--project", help="Flutter project folder relative to the repository root")
    parser.add_argument("--root", default=".", help="repository root")
    args = parser.parse_args()
    root = Path(args.root).resolve()
    project = find_project(root, args.project)
    print(f"Flutter project: {project}")
    android = project / "android"

    if not (android / "gradlew").is_file():
        run(["flutter", "create", "--platforms=android", "--org", "com.securescanai",
             "--project-name", "securescan_ai", "."], project)
    if not (android / "gradlew").is_file():
        sys.exit("ERROR: flutter create did not produce android/gradlew")

    # 1. application id / namespace
    changed = 0
    for path in android.rglob("*"):
        if path.is_file() and path.suffix in TEXT_SUFFIXES and "build" not in path.relative_to(android).parts[:1]:
            text = path.read_text(encoding="utf-8", errors="ignore")
            if GENERATED_ID in text:
                path.write_text(text.replace(GENERATED_ID, APP_ID), encoding="utf-8")
                changed += 1
    generated_dir = android / "app" / "src" / "main" / "kotlin" / "com" / "securescanai" / "securescan_ai"
    if generated_dir.is_dir():
        shutil.rmtree(generated_dir)
    print(f"Application id set to {APP_ID} ({changed} file(s) updated)")

    # 2. committed overrides
    overrides = project / "android_overrides"
    copied = 0
    for src in overrides.rglob("*"):
        if src.is_file():
            dest = android / src.relative_to(overrides)
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dest)
            copied += 1
    print(f"Copied {copied} override file(s)")

    # 3. verification
    gradle = next((p for p in (android / "app" / "build.gradle.kts", android / "app" / "build.gradle") if p.is_file()), None)
    if gradle is None or APP_ID not in gradle.read_text(encoding="utf-8"):
        sys.exit(f"ERROR: {APP_ID} was not found in the app Gradle file; the Flutter template may have changed.")
    if not (android / "app/src/main/kotlin/com/securescanai/app/MainActivity.kt").is_file():
        sys.exit("ERROR: MainActivity.kt is missing")
    print("Android platform is ready.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
